import { toPascalCase } from './spec'

const HEADER = '// Generated by site-to-api gen from specs/. Do not edit: run `site-to-api gen` again.\n'

/** An extract parser with the names it is exported under. */
export interface NamedExtract extends ExtractOperation {
  host: string
  functionName: string
  schemaName: string
  typeName: string
  specName: string
}

/**
 * Base for the names of an operation's parser: PascalCase letters and digits only, never empty
 * and never starting with a digit, so `extract<Base>`, `z<Base>Record` and `<base>Spec` are all
 * identifiers that cannot clash with the module's imports.
 */
function nameBase(value: string): string {
  const pascal = toPascalCase(value)
  if (pascal === '')
    return 'Operation'
  return /^\d/.test(pascal)
    ? `Op${pascal}`
    : pascal
}

/**
 * `SubmissionsFromGetRoot` when the spec says what its records are, else the operation alone
 * (`GetPrices`).
 */
function extractBase(operation: ExtractOperation): string {
  const base = nameBase(operation.operationId)
  const kind = operation.spec.kind === 'html' && operation.spec.recordsName !== undefined
    ? toPascalCase(operation.spec.recordsName)
    : ''
  return /^[A-Z][A-Za-z\d]*$/.test(kind)
    ? `${kind}From${base}`
    : base
}

/**
 * Names each parser after the records it returns and its operation (`extractDealsFromGetDeals`),
 * or after the operation alone when the page does not say what its records are (`extractGetPrices`). Operation ids are unique per host
 * only, so a clash across hosts is resolved by prefixing the host identifier. Ids that differ
 * only in punctuation (`get-a`, `getA`) can still meet; a numeric suffix keeps them apart.
 */
export function nameExtracts(hosts: HostSpec[], warnings: string[]): NamedExtract[] {
  const hostsByBase = new Map<string, Set<string>>()
  for (const host of hosts) {
    for (const operation of host.extracts) {
      const base = extractBase(operation)
      hostsByBase.set(base, (hostsByBase.get(base) ?? new Set()).add(host.host))
    }
  }
  const named: NamedExtract[] = []
  const taken = new Set<string>()
  for (const host of hosts) {
    for (const operation of host.extracts) {
      let base = extractBase(operation)
      if ((hostsByBase.get(base)?.size ?? 0) > 1) {
        // Host identifiers can start with `_1`; nameBase keeps the result an identifier.
        const prefixed = nameBase(`${host.identifier}_${base}`)
        warnings.push(`the parser name extract${base} would be the same on several hosts; for ${operation.operationId} on ${host.host} it is extract${prefixed}`)
        base = prefixed
      }
      let unique = base
      for (let n = 2; taken.has(unique); n++)
        unique = `${base}${n}`
      taken.add(unique)
      named.push({
        ...operation,
        host: host.host,
        functionName: `extract${unique}`,
        schemaName: `z${unique}Record`,
        typeName: `${unique}Record`,
        specName: `${unique.charAt(0).toLowerCase()}${unique.slice(1)}Spec`,
      })
    }
  }
  return named.sort((a, b) => a.functionName.localeCompare(b.functionName))
}

/**
 * A JavaScript string literal. JSON text is valid JavaScript since ES2019, but U+2028 and U+2029
 * still end a line in older parsers and editors, so they are written as escapes.
 */
function literal(value: unknown, indent?: number): string {
  return JSON.stringify(value, null, indent)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
}

/**
 * `client/extract.ts`: one parser and one Zod record schema per HTML/text operation, and one
 * reader per value that flows.json says comes from an HTML page.
 */
export function renderExtractModule(extracts: NamedExtract[], htmlValues: NamedHtmlValue[] = []): string {
  if (extracts.length === 0 && htmlValues.length === 0)
    return `${HEADER}\n// No operation in specs/ has an HTML or text response with an extraction spec,\n// and flows.json reads no value from an HTML page.\nexport {}\n`
  const recordBlocks = extracts.map((entry) => {
    const many = entry.spec.kind === 'text' || entry.spec.many
    const returns = many
      ? `${entry.typeName}[]`
      : entry.typeName
    const schema = many
      ? `z.array(${entry.schemaName})`
      : entry.schemaName
    // Every value here comes from the site; commentText keeps it from closing the comment.
    const where = commentText(`\`${entry.operationId}\` (${entry.method} ${entry.path} on ${entry.host}, ${entry.mimeType})`)
    return [
      `/** One record parsed from ${where}. */`,
      `export const ${entry.schemaName} = ${renderRecordSchema(entry.spec)}`,
      '',
      `export type ${entry.typeName} = z.infer<typeof ${entry.schemaName}>`,
      '',
      `const ${entry.specName}: ExtractSpec = ${literal(entry.spec, 2)}`,
      '',
      `/**`,
      ` * Parses the ${commentText(entry.mimeType)} response of ${where}.`,
      ` * Missing required fields are \`null\`; missing optional fields are left out.`,
      ` */`,
      `export function ${entry.functionName}(text: string): ${returns} {`,
      `  return ${schema}.parse(extract(text, ${entry.specName}))`,
      `}`,
    ].join('\n')
  })
  const valueBlocks = htmlValues.map(renderHtmlValue)
  const runtimeImports = [
    ...(extracts.length > 0
      ? ['extract']
      : []),
    ...(htmlValues.length > 0
      ? ['extractValue']
      : []),
  ]
  return [
    HEADER,
    ...(extracts.length > 0
      ? [`import type { ExtractSpec } from '@site-to-api/runtime'`]
      : []),
    `import { ${runtimeImports.join(', ')} } from '@site-to-api/runtime'`,
    ...(extracts.length > 0
      ? [`import * as z from 'zod'`]
      : []),
    '',
    [
      ...recordBlocks,
      ...valueBlocks,
    ].join('\n\n'),
    '',
  ].join('\n')
}

function describeLocation(location: NamedHtmlValue['location']): string {
  const parts = [`\`${location.selector}\``]
  parts.push(location.attr === null
    ? 'its text'
    : `attribute \`${location.attr}\``)
  if (location.pattern !== null)
    parts.push(`first group of \`${location.pattern}\``)
  return parts.join(', ')
}

function renderHtmlValue(value: NamedHtmlValue): string {
  // Selectors, patterns and operation ids come from the site; commentText keeps them inside.
  const lines = [
    `/**`,
    ` * Reads ${commentText(`\`${value.input}\``)} for ${commentText(value.usedBy.map(id => `\`${id}\``).join(', '))} from the HTML of`,
    ` * ${commentText(`\`${value.sourceOperationId}\``)}: ${commentText(describeLocation(value.location))}.`,
    ` * Returns \`null\` when the page has no such value.`,
  ]
  if (value.confidence === 'low')
    lines.push(` * flows.json rates this location low confidence: check it against the page.`)
  if (value.alternatives.length > 0)
    lines.push(` * flows.json also saw ${commentText(value.alternatives.map(describeLocation).join('; '))}.`)
  lines.push(
    ` */`,
    `export function ${value.functionName}(html: string): string | null {`,
    `  return extractValue(html, ${literal(value.location)})`,
    `}`,
  )
  return lines.join('\n')
}

function renderRecordSchema(spec: ExtractSpec): string {
  const fields: Array<[string, Pick<ExtractField, 'type' | 'optional'>]> = Object.entries(spec.fields)
  if (fields.length === 0)
    return 'z.object({})'
  const lines = fields.map(([name, field]) => {
    // Values that cannot be coerced become null, so every field is nullable.
    const base = `${zodForType(field.type)}.nullable()`
    return `  ${literal(name)}: ${field.optional
      ? `${base}.optional()`
      : base},`
  })
  return `z.object({\n${lines.join('\n')}\n})`
}

function zodForType(type: FieldType): string {
  switch (type) {
    case 'number':
      return 'z.number()'
    case 'integer':
      return 'z.number().int()'
    case 'boolean':
      return 'z.boolean()'
    // Dates are ISO strings when the runtime could read them, the original text otherwise.
    case 'date':
    case 'string':
      return 'z.string()'
  }
}

/**
 * The `sdk` of one host: hey-api's functions, with the GraphQL (decision 0027) and dispatcher
 * (decision 0039) wrappers in place of the raw functions of the same name.
 */
/** Header names of the host's apiKey schemes, lower case and sorted: credentials the runtime keeps on the site's origin. */
function credentialHeaders(host: HostSpec): string[] {
  return [
    ...new Set(host.auth.flatMap(scheme => scheme.type === 'apiKey' && scheme.in === 'header' && scheme.parameter !== null
      ? [
          scheme.parameter.toLowerCase(),
        ]
      : [])),
  ].sort()
}

function sdkEntry(host: HostSpec): string {
  const wrappers = [
    ...(host.graphql.length > 0
      ? [`${host.identifier}Graphql`]
      : []),
    ...(host.dispatch.length > 0
      ? [`${host.identifier}Dispatch`]
      : []),
  ]
  return wrappers.length === 0
    ? `    sdk: ${host.identifier},`
    : `    sdk: { ...${[host.identifier, ...wrappers].join(', ...')} },`
}

/** `client/index.ts`: every host's SDK under its namespace, plus `createSiteClient`. */
export function renderIndexModule(hosts: HostSpec[], extracts: NamedExtract[], htmlValues: NamedHtmlValue[] = []): string {
  // `.js` specifiers work under `moduleResolution: bundler` and `nodenext` alike.
  const imports = hosts.flatMap(host => [
    `import * as ${host.identifier} from './${host.identifier}/index.js'`,
    `import { client as ${host.identifier}Client } from './${host.identifier}/client.gen.js'`,
    ...(host.graphql.length > 0
      ? [`import * as ${host.identifier}Graphql from './${host.identifier}/graphql.js'`]
      : []),
    ...(host.dispatch.length > 0
      ? [`import * as ${host.identifier}Dispatch from './${host.identifier}/dispatch.js'`]
      : []),
  ])
  // GraphQL functions take `{ variables }` and replace the raw SDK functions of the same name.
  const entries = hosts.map(host => [
    `  ${literal(host.host)}: {`,
    `    client: ${host.identifier}Client,`,
    sdkEntry(host),
    `  },`,
  ].join('\n'))
  const defaults = hosts.map(host => [
    `  ${literal(host.host)}: {`,
    `    baseUrl: ${literal(host.baseUrl)},`,
    `    headers: ${renderStringRecord(host.defaultHeaders, '    ')},`,
    `    credentialHeaders: ${literal(credentialHeaders(host))},`,
    `  },`,
  ].join('\n'))
  const contentTypes = renderContentTypes(hosts)
  const extractValues = [
    ...extracts.flatMap(entry => [entry.functionName, entry.schemaName]),
    ...htmlValues.map(value => value.functionName),
  ].sort()
  const extractExports = [
    ...(extractValues.length === 0
      ? []
      : [`export { ${extractValues.join(', ')} } from './extract.js'`]),
    ...(extracts.length === 0
      ? []
      : [`export type { ${extracts.map(entry => entry.typeName).sort().join(', ')} } from './extract.js'`]),
  ]

  return [
    HEADER,
    `import type { RetryOptions, Session } from '@site-to-api/runtime'`,
    `import { CookieJar, createFetch } from '@site-to-api/runtime'`,
    ...imports,
    '',
    `export { ${hosts.map(host => host.identifier).join(', ')} }`,
    ...extractExports,
    `export { browserSession, combineSessions, CookieJar, cookieSession, extractValue, isSiteApiError, SiteApiError, tokenSession } from '@site-to-api/runtime'`,
    `export type { BrowserCookie, Session } from '@site-to-api/runtime'`,
    '',
    `const sdks = {\n${entries.join('\n')}\n}`,
    '',
    `/** Hosts this client was generated for. */`,
    `export type SiteHost = keyof typeof sdks`,
    '',
    `/** Per host: the base URL, the constant headers, and the headers that carry credentials (dropped on a redirect to another origin). */`,
    `const hostDefaults: Record<SiteHost, { baseUrl: string, headers: Record<string, string>, credentialHeaders: string[] }> = {\n${defaults.join('\n')}\n}`,
    '',
    ...contentTypes.declarations,
    `/** A security scheme of the spec, as the client passes it to {@link SiteClientOptions.auth}. */`,
    `export interface SiteAuthScheme {`,
    `  type: 'apiKey' | 'http'`,
    `  /** Where the value goes; defaults to a header. */`,
    `  in?: 'header' | 'query' | 'cookie'`,
    `  /** Header, query or cookie name; defaults to \`Authorization\`. */`,
    `  name?: string`,
    `  scheme?: 'basic' | 'bearer'`,
    `}`,
    '',
    `/** Options for {@link createSiteClient}. */`,
    `export interface SiteClientOptions<H extends SiteHost> {`,
    `  host: H`,
    `  /** How requests authenticate; defaults to the cookies in \`jar\` (see README.md). */`,
    `  session?: Session`,
    `  /**`,
    `   * Credentials for the operations whose spec declares \`security\`, called before each of them.`,
    `   * For an \`apiKey\` scheme the value is sent as-is (include \`Bearer \` when the site expects`,
    `   * it); for \`http\` bearer the client adds \`Bearer \`. Return \`undefined\` to send nothing.`,
    `   * Works alongside \`session\`, e.g. browser cookies plus a token from the login response.`,
    `   */`,
    `  auth?: string | ((scheme: SiteAuthScheme) => string | undefined | Promise<string | undefined>)`,
    `  /** Cookie jar; defaults to the session's jar or a new one. Persist it with \`jar.toJSON()\`. */`,
    `  jar?: CookieJar`,
    `  /** Underlying fetch; defaults to \`globalThis.fetch\`. */`,
    `  fetch?: typeof fetch`,
    `  /** Overrides the base URL from the spec, e.g. for a staging host or a test server. */`,
    `  baseUrl?: string`,
    `  retry?: RetryOptions | false`,
    `  /** Extra headers for every request; they override the constant headers from the spec. */`,
    `  headers?: Record<string, string>`,
    `}`,
    '',
    `/** A configured host: its SDK functions use \`fetch\` (cookie jar, session, retries). */`,
    `export interface SiteClient<H extends SiteHost> {`,
    `  host: H`,
    `  client: (typeof sdks)[H]['client']`,
    `  sdk: (typeof sdks)[H]['sdk']`,
    `  jar: CookieJar`,
    `  fetch: typeof fetch`,
    `}`,
    '',
    `/**`,
    ` * Configures the shared hey-api client of \`host\` to send requests through the runtime's`,
    ` * \`createFetch\`: cookies from \`jar\`, the session's credentials, \`auth\` for secured`,
    ` * operations, retries with backoff and the constant headers captured for that host. Every SDK`,
    ` * function of the host then uses it.`,
    ` *`,
    ` * There is one configuration per host: calling it again for the same host replaces the`,
    ` * previous configuration, also for the \`sdk\` the earlier call returned.`,
    ` */`,
    `export function createSiteClient<H extends SiteHost>(options: SiteClientOptions<H>): SiteClient<H> {`,
    `  const defaults = hostDefaults[options.host]`,
    `  const jar = options.jar ?? options.session?.jar ?? new CookieJar()`,
    `  const siteFetch = createFetch({`,
    `    jar,`,
    `    session: options.session,`,
    `    fetch: options.fetch,`,
    `    retry: options.retry,`,
    `    defaultHeaders: { ...defaults.headers, ...options.headers },`,
    `    credentialHeaders: defaults.credentialHeaders,`,
    `  })`,
    `  const { client, sdk } = sdks[options.host]`,
    `  // \`auth\` is always set so a second call without it clears the first call's credentials.`,
    `  client.setConfig({ baseUrl: options.baseUrl ?? defaults.baseUrl, fetch: siteFetch, auth: options.auth })`,
    ...contentTypes.setup,
    `  return { host: options.host, client, sdk, jar, fetch: siteFetch }`,
    `}`,
    '',
  ].join('\n')
}

/**
 * Code for operations whose JSON body the site sends under another content type (Algolia's JSON
 * as `application/x-www-form-urlencoded`). hey-api serializes the body as JSON and labels it
 * `application/json`; a request interceptor puts back the site's content type. Nothing is written
 * when no operation needs it, so most clients do not change.
 */
function renderContentTypes(hosts: HostSpec[]): { declarations: string[], setup: string[] } {
  if (hosts.every(host => Object.keys(host.sentContentTypes).length === 0))
    return { declarations: [], setup: [] }
  const entries = hosts.map(host => `  ${literal(host.host)}: ${renderStringRecord(host.sentContentTypes, '  ')},`)
  return {
    declarations: [
      `/**`,
      ` * Operations (\`METHOD /path\`) whose body is JSON text the site sends under another`,
      ` * content type. The server may reject the same body labelled \`application/json\`.`,
      ` */`,
      `const sentContentTypes: Record<SiteHost, Record<string, string>> = {\n${entries.join('\n')}\n}`,
      '',
      `/** Hosts whose client already has the content-type interceptor (it is added once). */`,
      `const contentTypeHosts = new Set<SiteHost>()`,
      '',
    ],
    setup: [
      `  const contentTypes = sentContentTypes[options.host]`,
      `  if (Object.keys(contentTypes).length > 0 && !contentTypeHosts.has(options.host)) {`,
      `    contentTypeHosts.add(options.host)`,
      `    client.interceptors.request.use((request, opts) => {`,
      `      const sent = contentTypes[\`\${opts.method} \${opts.url}\`]`,
      `      // Replaces the SDK's own \`application/json\` label. A caller who passes another content`,
      `      // type keeps it; one who passes exactly \`application/json\` cannot be told from the SDK's`,
      `      // label, so it is replaced too.`,
      `      if (sent !== undefined && request.headers.get('content-type') === 'application/json')`,
      `        request.headers.set('content-type', sent)`,
      `      return request`,
      `    })`,
      `  }`,
    ],
  }
}

function renderStringRecord(record: Record<string, string>, indent: string): string {
  const entries = Object.entries(record)
  if (entries.length === 0)
    return '{}'
  return `{\n${entries.map(([key, value]) => `${indent}  ${literal(key)}: ${literal(value)},`).join('\n')}\n${indent}}`
}

/** Inline examples longer than this are left to the AsyncAPI file. */
const MAX_README_EXAMPLE = 400
const README_ROLES = { init: 'start the protocol', auth: 'authenticate', subscribe: 'subscribe' } as const

function channelLine(channel: ChannelSummary): string {
  const steps = channel.handshake.map((step) => {
    const json = step.example === null
      ? null
      : typeof step.example === 'string'
        ? step.example
        : JSON.stringify(step.example)
    const role = step.role === null || step.role === 'other'
      ? ''
      : ` to ${README_ROLES[step.role]}`
    return json !== null && json !== undefined && json.length <= MAX_README_EXAMPLE
      ? `${code(step.name)}${role} (${code(json)})`
      : `${code(step.name)}${role}`
  })
  let after = 'the client sent nothing during capture; the server pushes on its own'
  if (steps.length > 0)
    after = `after connecting, send ${steps.join(', then ')}`
  else if (channel.messageTypes === 0)
    after = 'no messages were seen during capture'
  return `- ${code(channel.url)} (channel ${code(channel.id)} in ${code(`../specs/${channel.file}`)}): ${after}.`
}

function channelsReadme(channels: readonly ChannelSummary[]): string[] {
  if (channels.length === 0)
    return []
  return [
    '## Real-time channels',
    '',
    'The site also uses WebSockets. The generated code covers HTTP only; open these with any',
    'WebSocket client, sending the session\'s cookies when the AsyncAPI file lists them',
    '(`x-site-to-api-cookies`).',
    '',
    ...channels.map(channelLine),
    '',
  ]
}

