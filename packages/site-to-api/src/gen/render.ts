const HEADER = '// Generated by site-to-api gen from specs/. Do not edit: run `site-to-api gen` again.\n'

/** An extract parser with the names it is exported under. */
export interface NamedExtract extends ExtractOperation {
  host: string
  functionName: string
  schemaName: string
  typeName: string
  specName: string
}

/**
 * Base for the names of an operation's parser: PascalCase letters and digits only, never empty
 * and never starting with a digit, so `extract<Base>`, `z<Base>Record` and `<base>Spec` are all
 * identifiers that cannot clash with the module's imports.
 */
function nameBase(value: string): string {
  const pascal = toPascalCase(value)
  if (pascal === '')
    return 'Operation'
  return /^\d/.test(pascal)
    ? `Op${pascal}`
    : pascal
}

/**
 * `SubmissionsFromGetRoot` when the spec says what its records are, else the operation alone
 * (`GetPrices`).
 */
function extractBase(operation: ExtractOperation): string {
  const base = nameBase(operation.operationId)
  const kind = operation.spec.kind === 'html' && operation.spec.recordsName !== undefined
    ? toPascalCase(operation.spec.recordsName)
    : ''
  return /^[A-Z][A-Za-z\d]*$/.test(kind)
    ? `${kind}From${base}`
    : base
}

/**
 * Names each parser after the records it returns and its operation (`extractDealsFromGetDeals`),
 * or after the operation alone when the page does not say what its records are (`extractGetPrices`). Operation ids are unique per host
 * only, so a clash across hosts is resolved by prefixing the host identifier. Ids that differ
 * only in punctuation (`get-a`, `getA`) can still meet; a numeric suffix keeps them apart.
 */
export function nameExtracts(hosts: HostSpec[], warnings: string[]): NamedExtract[] {
  const hostsByBase = new Map<string, Set<string>>()
  for (const host of hosts) {
    for (const operation of host.extracts) {
      const base = extractBase(operation)
      hostsByBase.set(base, (hostsByBase.get(base) ?? new Set()).add(host.host))
    }
  }
  const named: NamedExtract[] = []
  const taken = new Set<string>()
  for (const host of hosts) {
    for (const operation of host.extracts) {
      let base = extractBase(operation)
      if ((hostsByBase.get(base)?.size ?? 0) > 1) {
        // Host identifiers can start with `_1`; nameBase keeps the result an identifier.
        const prefixed = nameBase(`${host.identifier}_${base}`)
        warnings.push(`the parser name extract${base} would be the same on several hosts; for ${operation.operationId} on ${host.host} it is extract${prefixed}`)
        base = prefixed
      }
      let unique = base
      for (let n = 2; taken.has(unique); n++)
        unique = `${base}${n}`
      taken.add(unique)
      named.push({
        ...operation,
        host: host.host,
        functionName: `extract${unique}`,
        schemaName: `z${unique}Record`,
        typeName: `${unique}Record`,
        specName: `${unique.charAt(0).toLowerCase()}${unique.slice(1)}Spec`,
      })
    }
  }
  return named.sort((a, b) => a.functionName.localeCompare(b.functionName))
}

/**
 * A JavaScript string literal. JSON text is valid JavaScript since ES2019, but U+2028 and U+2029
 * still end a line in older parsers and editors, so they are written as escapes.
 */
function literal(value: unknown, indent?: number): string {
  return JSON.stringify(value, null, indent)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
}

/**
 * `client/extract.ts`: one parser and one Zod record schema per HTML/text operation, and one
 * reader per value that flows.json says comes from an HTML page.
 */
export function renderExtractModule(extracts: NamedExtract[], htmlValues: NamedHtmlValue[] = []): string {
  if (extracts.length === 0 && htmlValues.length === 0)
    return `${HEADER}\n// No operation in specs/ has an HTML or text response with an extraction spec,\n// and flows.json reads no value from an HTML page.\nexport {}\n`
  const recordBlocks = extracts.map((entry) => {
    const many = entry.spec.kind === 'text' || entry.spec.many
    const returns = many
      ? `${entry.typeName}[]`
      : entry.typeName
    const schema = many
      ? `z.array(${entry.schemaName})`
      : entry.schemaName
    // Every value here comes from the site; commentText keeps it from closing the comment.
    const where = commentText(`\`${entry.operationId}\` (${entry.method} ${entry.path} on ${entry.host}, ${entry.mimeType})`)
    return [
      `/** One record parsed from ${where}. */`,
      `export const ${entry.schemaName} = ${pure(renderRecordSchema(entry.spec))}`,
      '',
      `export type ${entry.typeName} = z.infer<typeof ${entry.schemaName}>`,
      '',
      `const ${entry.specName}: ExtractSpec = ${literal(entry.spec, 2)}`,
      '',
      `/**`,
      ` * Parses the ${commentText(entry.mimeType)} response of ${where}.`,
      ` * Missing required fields are \`null\`; missing optional fields are left out.`,
      ` */`,
      `export function ${entry.functionName}(text: string): ${returns} {`,
      `  return ${schema}.parse(extract(text, ${entry.specName}))`,
      `}`,
    ].join('\n')
  })
  const valueBlocks = htmlValues.map(renderHtmlValue)
  const runtimeImports = [
    ...(extracts.length > 0
      ? ['extract']
      : []),
    ...(htmlValues.length > 0
      ? ['extractValue']
      : []),
  ]
  return [
    HEADER,
    ...(extracts.length > 0
      ? [`import type { ExtractSpec } from '@site-to-api/runtime'`]
      : []),
    `import { ${runtimeImports.join(', ')} } from '@site-to-api/runtime'`,
    ...(extracts.length > 0
      ? [`import * as z from 'zod/mini'`]
      : []),
    '',
    [
      ...recordBlocks,
      ...valueBlocks,
    ].join('\n\n'),
    '',
  ].join('\n')
}

function describeLocation(location: NamedHtmlValue['location']): string {
  const parts = [`\`${location.selector}\``]
  parts.push(location.attr === null
    ? 'its text'
    : `attribute \`${location.attr}\``)
  if (location.pattern !== null)
    parts.push(`first group of \`${location.pattern}\``)
  return parts.join(', ')
}

function renderHtmlValue(value: NamedHtmlValue): string {
  // Selectors, patterns and operation ids come from the site; commentText keeps them inside.
  const lines = [
    `/**`,
    ` * Reads ${commentText(`\`${value.input}\``)} for ${commentText(value.usedBy.map(id => `\`${id}\``).join(', '))} from the HTML of`,
    ` * ${commentText(`\`${value.sourceOperationId}\``)}: ${commentText(describeLocation(value.location))}.`,
    ` * Returns \`null\` when the page has no such value.`,
  ]
  if (value.confidence === 'low')
    lines.push(` * flows.json rates this location low confidence: check it against the page.`)
  if (value.alternatives.length > 0)
    lines.push(` * flows.json also saw ${commentText(value.alternatives.map(describeLocation).join('; '))}.`)
  lines.push(
    ` */`,
    `export function ${value.functionName}(html: string): string | null {`,
    `  return extractValue(html, ${literal(value.location)})`,
    `}`,
  )
  return lines.join('\n')
}

/**
 * `expression` evaluated in a call marked `@__PURE__`, so a bundler drops a module-level schema
 * nobody imports: a plain `z.object(…)` call counts as a side effect and would always stay
 * (decision 0057).
 */
export function pure(expression: string): string {
  return `/* @__PURE__ */ (() => ${expression})()`
}

function renderRecordSchema(spec: ExtractSpec): string {
  const fields: Array<[string, Pick<ExtractField, 'type' | 'optional'>]> = Object.entries(spec.fields)
  if (fields.length === 0)
    return 'z.object({})'
  const lines = fields.map(([name, field]) => {
    // Values that cannot be coerced become null, so every field is nullable.
    const base = `z.nullable(${zodForType(field.type)})`
    return `  ${literal(name)}: ${field.optional
      ? `z.optional(${base})`
      : base},`
  })
  return `z.object({\n${lines.join('\n')}\n})`
}

function zodForType(type: FieldType): string {
  switch (type) {
    case 'number':
      return 'z.number()'
    case 'integer':
      return 'z.int()'
    case 'boolean':
      return 'z.boolean()'
    // Dates are ISO strings when the runtime could read them, the original text otherwise.
    case 'date':
    case 'string':
      return 'z.string()'
  }
}

/**
 * The `sdk` of one host: hey-api's functions, with the GraphQL (decision 0027) and dispatcher
 * (decision 0039) wrappers in place of the raw functions of the same name.
 */
/** Header names of the host's apiKey schemes, lower case and sorted: credentials the runtime keeps on the site's origin. */
function credentialHeaders(host: HostSpec): string[] {
  return [
    ...new Set(host.auth.flatMap(scheme => scheme.type === 'apiKey' && scheme.in === 'header' && scheme.parameter !== null
      ? [
          scheme.parameter.toLowerCase(),
        ]
      : [])),
  ].sort()
}

/** An SDK function a host exports, as `createSiteClient` binds it to its own client. */
export interface HostFunction {
  name: string
  /** The module that exports it: hey-api's SDK, or a GraphQL or dispatcher wrapper of the same name. */
  module: 'sdk' | 'graphql' | 'dispatch'
  /** Generic in `ThrowOnError`, as hey-api's functions and the wrappers are. */
  generic: boolean
}

const EXPORTED_FUNCTION = /^export (?:const|function) ([A-Za-z_$][\w$]*)(?: = )?(<ThrowOnError extends boolean)?/gm

/** The functions a generated module exports (`sdk.gen.ts`, `graphql.ts`, `dispatch.ts`). */
export function exportedFunctions(source: string, module: HostFunction['module']): HostFunction[] {
  return [
    ...source.matchAll(EXPORTED_FUNCTION),
  ].flatMap(match => match[1] === undefined
    ? []
    : [
        { name: match[1], module, generic: match[2] !== undefined },
      ])
}

/** `localhost_4173` → `Localhost4173`, `github_com` → `GithubCom`: per-host names in generated code. */
function hostPascal(identifier: string): string {
  const name = identifier.split('_').filter(part => part !== '').map(part => `${part.charAt(0).toUpperCase()}${part.slice(1)}`).join('')
  // An IP address host (`_127_0_0_1`) would start with a digit, which no identifier may.
  return /^[A-Z]/i.test(name)
    ? name
    : `Host${name}`
}

/** `createGithubComClient`: the per-host factory in `<host>/site.ts`. */
function hostFactoryName(identifier: string): string {
  return `create${hostPascal(identifier)}Client`
}

/** The functions a host exposes: each name once, a GraphQL or dispatcher wrapper over hey-api's. */
function boundFunctions(functions: readonly HostFunction[]): HostFunction[] {
  const byName = new Map<string, HostFunction>()
  for (const fn of functions) {
    const known = byName.get(fn.name)
    if (known === undefined || known.module === 'sdk')
      byName.set(fn.name, fn)
  }
  return [
    ...byName.values(),
  ].sort((a, b) => a.name < b.name
    ? -1
    : a.name > b.name
      ? 1
      : 0)
}

const MODULE_FILES: Record<HostFunction['module'], string> = {
  sdk: './sdk.gen.js',
  graphql: './graphql.js',
  dispatch: './dispatch.js',
}

/** `bind<Host>(client)`: every function of the host with `client` filled in. */
function renderBinder(host: HostSpec, functions: readonly HostFunction[]): string[] {
  const id = host.identifier
  const lines = boundFunctions(functions).map((fn) => {
    const target = `${id}Site.${fn.name}`
    return fn.generic
      ? `    ${fn.name}: <ThrowOnError extends boolean = false>(...[options]: Parameters<typeof ${target}<ThrowOnError>>) => ${target}<ThrowOnError>({ ...options, client }),`
      : `    ${fn.name}: (...[options]: Parameters<typeof ${target}>) => ${target}({ ...options, client }),`
  })
  return [
    `/** The functions of ${host.host}, sending through \`client\` instead of hey-api's shared default one. */`,
    `function bind${hostPascal(id)}(client: ${hostPascal(id)}Client['client']) {`,
    `  return {`,
    ...lines,
    `  }`,
    `}`,
    '',
  ]
}

