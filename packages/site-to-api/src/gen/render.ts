/**
 * Renders the files `gen` writes next to hey-api's output: `extract.ts`, `index.ts` and
 * `README.md`. Pure string builders, so the output is easy to test and byte-for-byte stable.
 */
import type { ExtractField, ExtractSpec, FieldType } from '@site-to-api/runtime'
import type { SessionRequirement } from '../model'
import type { ChannelSummary, ExtractOperation, HostSpec } from './spec'
import { code, codeBlock, commentText, text } from '../emit/escape'
import { sdkFunctionName } from '../emit/naming'
import { toPascalCase } from './spec'

const HEADER = '// Generated by site-to-api gen from specs/. Do not edit: run `site-to-api gen` again.\n'

/** An extract parser with the names it is exported under. */
export interface NamedExtract extends ExtractOperation {
  host: string
  functionName: string
  schemaName: string
  typeName: string
  specName: string
}

/**
 * Base for the names of an operation's parser: PascalCase letters and digits only, never empty
 * and never starting with a digit, so `extract<Base>`, `z<Base>Record` and `<base>Spec` are all
 * identifiers that cannot clash with the module's imports.
 */
function nameBase(value: string): string {
  const pascal = toPascalCase(value)
  if (pascal === '')
    return 'Operation'
  return /^\d/.test(pascal)
    ? `Op${pascal}`
    : pascal
}

/**
 * Names each parser after its operation (`extractGetPrices`). Operation ids are unique per host
 * only, so a clash across hosts is resolved by prefixing the host identifier. Ids that differ
 * only in punctuation (`get-a`, `getA`) can still meet; a numeric suffix keeps them apart.
 */
export function nameExtracts(hosts: HostSpec[], warnings: string[]): NamedExtract[] {
  const hostsByBase = new Map<string, Set<string>>()
  for (const host of hosts) {
    for (const operation of host.extracts) {
      const base = nameBase(operation.operationId)
      hostsByBase.set(base, (hostsByBase.get(base) ?? new Set()).add(host.host))
    }
  }
  const named: NamedExtract[] = []
  const taken = new Set<string>()
  for (const host of hosts) {
    for (const operation of host.extracts) {
      let base = nameBase(operation.operationId)
      if ((hostsByBase.get(base)?.size ?? 0) > 1) {
        // Host identifiers can start with `_1`; nameBase keeps the result an identifier.
        const prefixed = nameBase(`${host.identifier}_${base}`)
        warnings.push(`operation ${operation.operationId} exists on several hosts; its parser for ${host.host} is extract${prefixed}`)
        base = prefixed
      }
      let unique = base
      for (let n = 2; taken.has(unique); n++)
        unique = `${base}${n}`
      taken.add(unique)
      named.push({
        ...operation,
        host: host.host,
        functionName: `extract${unique}`,
        schemaName: `z${unique}Record`,
        typeName: `${unique}Record`,
        specName: `${unique.charAt(0).toLowerCase()}${unique.slice(1)}Spec`,
      })
    }
  }
  return named.sort((a, b) => a.functionName.localeCompare(b.functionName))
}

/**
 * A JavaScript string literal. JSON text is valid JavaScript since ES2019, but U+2028 and U+2029
 * still end a line in older parsers and editors, so they are written as escapes.
 */
function literal(value: unknown, indent?: number): string {
  return JSON.stringify(value, null, indent)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
}

/** `client/extract.ts`: one parser and one Zod record schema per HTML/text operation. */
export function renderExtractModule(extracts: NamedExtract[]): string {
  if (extracts.length === 0)
    return `${HEADER}\n// No operation in specs/ has an HTML or text response with an extraction spec.\nexport {}\n`
  const blocks = extracts.map((entry) => {
    const many = entry.spec.kind === 'text' || entry.spec.many
    const returns = many
      ? `${entry.typeName}[]`
      : entry.typeName
    const schema = many
      ? `z.array(${entry.schemaName})`
      : entry.schemaName
    // Every value here comes from the site; commentText keeps it from closing the comment.
    const where = commentText(`\`${entry.operationId}\` (${entry.method} ${entry.path} on ${entry.host}, ${entry.mimeType})`)
    return [
      `/** One record parsed from ${where}. */`,
      `export const ${entry.schemaName} = ${renderRecordSchema(entry.spec)}`,
      '',
      `export type ${entry.typeName} = z.infer<typeof ${entry.schemaName}>`,
      '',
      `const ${entry.specName}: ExtractSpec = ${literal(entry.spec, 2)}`,
      '',
      `/**`,
      ` * Parses the ${commentText(entry.mimeType)} response of ${where}.`,
      ` * Missing required fields are \`null\`; missing optional fields are left out.`,
      ` */`,
      `export function ${entry.functionName}(text: string): ${returns} {`,
      `  return ${schema}.parse(extract(text, ${entry.specName}))`,
      `}`,
    ].join('\n')
  })
  return [
    HEADER,
    `import type { ExtractSpec } from '@site-to-api/runtime'`,
    `import { extract } from '@site-to-api/runtime'`,
    `import * as z from 'zod'`,
    '',
    blocks.join('\n\n'),
    '',
  ].join('\n')
}

function renderRecordSchema(spec: ExtractSpec): string {
  const fields: Array<[string, Pick<ExtractField, 'type' | 'optional'>]> = Object.entries(spec.fields)
  if (fields.length === 0)
    return 'z.object({})'
  const lines = fields.map(([name, field]) => {
    // Values that cannot be coerced become null, so every field is nullable.
    const base = `${zodForType(field.type)}.nullable()`
    return `  ${literal(name)}: ${field.optional
      ? `${base}.optional()`
      : base},`
  })
  return `z.object({\n${lines.join('\n')}\n})`
}

function zodForType(type: FieldType): string {
  switch (type) {
    case 'number':
      return 'z.number()'
    case 'integer':
      return 'z.number().int()'
    case 'boolean':
      return 'z.boolean()'
    // Dates are ISO strings when the runtime could read them, the original text otherwise.
    case 'date':
    case 'string':
      return 'z.string()'
  }
}

/** `client/index.ts`: every host's SDK under its namespace, plus `createSiteClient`. */
export function renderIndexModule(hosts: HostSpec[], extracts: NamedExtract[]): string {
  const imports = hosts.flatMap(host => [
    `import * as ${host.identifier} from './${host.identifier}/index'`,
    `import { client as ${host.identifier}Client } from './${host.identifier}/client.gen'`,
  ])
  const entries = hosts.map(host => [
    `  ${literal(host.host)}: {`,
    `    client: ${host.identifier}Client,`,
    `    sdk: ${host.identifier},`,
    `  },`,
  ].join('\n'))
  const defaults = hosts.map(host => [
    `  ${literal(host.host)}: {`,
    `    baseUrl: ${literal(host.baseUrl)},`,
    `    headers: ${renderStringRecord(host.defaultHeaders, '    ')},`,
    `  },`,
  ].join('\n'))
  const extractExports = extracts.length === 0
    ? []
    : [
        `export { ${extracts.flatMap(entry => [entry.functionName, entry.schemaName]).sort().join(', ')} } from './extract'`,
        `export type { ${extracts.map(entry => entry.typeName).sort().join(', ')} } from './extract'`,
      ]

  return [
    HEADER,
    `import type { RetryOptions, Session } from '@site-to-api/runtime'`,
    `import { CookieJar, createFetch } from '@site-to-api/runtime'`,
    ...imports,
    '',
    `export { ${hosts.map(host => host.identifier).join(', ')} }`,
    ...extractExports,
    `export { browserSession, CookieJar, cookieSession, isSiteApiError, SiteApiError, tokenSession } from '@site-to-api/runtime'`,
    `export type { BrowserCookie, Session } from '@site-to-api/runtime'`,
    '',
    `const sdks = {\n${entries.join('\n')}\n}`,
    '',
    `/** Hosts this client was generated for. */`,
    `export type SiteHost = keyof typeof sdks`,
    '',
    `const hostDefaults: Record<SiteHost, { baseUrl: string, headers: Record<string, string> }> = {\n${defaults.join('\n')}\n}`,
    '',
    `/** Options for {@link createSiteClient}. */`,
    `export interface SiteClientOptions<H extends SiteHost> {`,
    `  host: H`,
    `  /** How requests authenticate; defaults to the cookies in \`jar\` (see README.md). */`,
    `  session?: Session`,
    `  /** Cookie jar; defaults to the session's jar or a new one. Persist it with \`jar.toJSON()\`. */`,
    `  jar?: CookieJar`,
    `  /** Underlying fetch; defaults to \`globalThis.fetch\`. */`,
    `  fetch?: typeof fetch`,
    `  /** Overrides the base URL from the spec, e.g. for a staging host or a test server. */`,
    `  baseUrl?: string`,
    `  retry?: RetryOptions | false`,
    `  /** Extra headers for every request; they override the constant headers from the spec. */`,
    `  headers?: Record<string, string>`,
    `}`,
    '',
    `/** A configured host: its SDK functions use \`fetch\` (cookie jar, session, retries). */`,
    `export interface SiteClient<H extends SiteHost> {`,
    `  host: H`,
    `  client: (typeof sdks)[H]['client']`,
    `  sdk: (typeof sdks)[H]['sdk']`,
    `  jar: CookieJar`,
    `  fetch: typeof fetch`,
    `}`,
    '',
    `/**`,
    ` * Configures the shared hey-api client of \`host\` to send requests through the runtime's`,
    ` * \`createFetch\`: cookies from \`jar\`, the session's credentials, retries with backoff and the`,
    ` * constant headers captured for that host. Every SDK function of the host then uses it.`,
    ` */`,
    `export function createSiteClient<H extends SiteHost>(options: SiteClientOptions<H>): SiteClient<H> {`,
    `  const defaults = hostDefaults[options.host]`,
    `  const jar = options.jar ?? options.session?.jar ?? new CookieJar()`,
    `  const siteFetch = createFetch({`,
    `    jar,`,
    `    session: options.session,`,
    `    fetch: options.fetch,`,
    `    retry: options.retry,`,
    `    defaultHeaders: { ...defaults.headers, ...options.headers },`,
    `  })`,
    `  const { client, sdk } = sdks[options.host]`,
    `  client.setConfig({ baseUrl: options.baseUrl ?? defaults.baseUrl, fetch: siteFetch })`,
    `  return { host: options.host, client, sdk, jar, fetch: siteFetch }`,
    `}`,
    '',
  ].join('\n')
}

function renderStringRecord(record: Record<string, string>, indent: string): string {
  const entries = Object.entries(record)
  if (entries.length === 0)
    return '{}'
  return `{\n${entries.map(([key, value]) => `${indent}  ${literal(key)}: ${literal(value)},`).join('\n')}\n${indent}}`
}

/** Inline examples longer than this are left to the AsyncAPI file. */
const MAX_README_EXAMPLE = 400

function channelLine(channel: ChannelSummary): string {
  const steps = channel.handshake.map((step) => {
    const json = step.example === null
      ? null
      : typeof step.example === 'string'
        ? step.example
        : JSON.stringify(step.example)
    return json !== null && json !== undefined && json.length <= MAX_README_EXAMPLE
      ? `${code(step.name)} (${code(json)})`
      : code(step.name)
  })
  const after = steps.length > 0
    ? `after connecting, send ${steps.join(', then ')}`
    : 'the server pushes without a subscription message'
  return `- ${code(channel.url)} (channel ${code(channel.id)} in ${code(`../specs/${channel.file}`)}): ${after}.`
}

function channelsReadme(channels: readonly ChannelSummary[]): string[] {
  if (channels.length === 0)
    return []
  return [
    '## Real-time channels',
    '',
    'The site also uses WebSockets. The generated code covers HTTP only; open these with any',
    'WebSocket client, sending the session\'s cookies when the AsyncAPI file lists them',
    '(`x-site-to-api-cookies`).',
    '',
    ...channels.map(channelLine),
    '',
  ]
}

/** `client/README.md`: how to create a client for each host, which session it needs and the WebSocket channels. */
export function renderReadme(hosts: HostSpec[], extracts: NamedExtract[], sessions: SessionRequirement[], channels: readonly ChannelSummary[] = []): string {
  const sections = hosts.map(host => renderHostSection(host, sessions.find(session => session.host === host.host) ?? null))
  const parsers = extracts.length === 0
    ? ['No operation has an HTML or text response with an extraction spec.']
    : extracts.map(entry => `- ${code(`${entry.functionName}(text)`)} → ${code(`${entry.typeName}${entry.spec.kind === 'text' || entry.spec.many
        ? '[]'
        : ''}`)}: ${code(entry.operationId)} (${code(`${entry.method} ${entry.path}`)} on ${code(entry.host)}, ${text(entry.mimeType)}). Schema: ${code(entry.schemaName)}.`)
  return [
    '# Generated client',
    '',
    'Generated by `site-to-api gen` from `../specs/` and `../flows.json`. Do not edit these files:',
    'run `site-to-api gen` again after `build` or `probe`.',
    '',
    'The code imports `@site-to-api/runtime` and `zod` (v4); add both to your project.',
    'Each host folder holds the hey-api output (types, SDK functions, Zod schemas). `index.ts` exports',
    'every host\'s SDK as a namespace and `createSiteClient()`, which routes that host\'s SDK through',
    'the runtime: a cookie jar, the session below, retries with backoff and the constant headers.',
    '',
    '## Hosts',
    '',
    sections.join('\n\n'),
    '',
    '## Parsing HTML and text responses',
    '',
    ...parsers,
    '',
    ...channelsReadme(channels),
  ].join('\n')
}

/** SDK function names hey-api derives (see emit/naming); only plain identifiers go into the example. */
const PLAIN_IDENTIFIER = /^[a-z_$][\w$]*$/i

function renderHostSection(host: HostSpec, session: SessionRequirement | null): string {
  const example = host.operationIds.map(sdkFunctionName).find(name => PLAIN_IDENTIFIER.test(name)) ?? 'someOperation'
  const lines = [
    `### ${text(host.host)}`,
    '',
    `- Namespace ${code(host.identifier)}, base URL ${code(host.baseUrl)}, ${host.operationIds.length} operation${host.operationIds.length === 1
      ? ''
      : 's'}.`,
    `- Session: ${describeSession(session)}`,
  ]
  if (session && session.cookies.length > 0) {
    const cookies = session.cookies.map((cookie) => {
      if (cookie.source === 'browser')
        return `${code(cookie.name)} (set by the browser, not by an API response)`
      if (cookie.source === 'script')
        return `${code(cookie.name)} (set by a page script; derive its value and set it yourself)`
      if (cookie.source === 'unknown')
        return `${code(cookie.name)} (present in the browser profile; origin unknown)`
      return cookie.setBy
        ? `${code(cookie.name)} (set by ${code(cookie.setBy)})`
        : code(cookie.name)
    })
    lines.push(`- Cookies the API needs: ${cookies.join(', ')}.`)
  }
  if (session && session.botProtection.length > 0)
    lines.push(`- Bot protection: ${session.botProtection.map(entry => `${text(entry.vendor)} (${text(entry.evidence)})`).join(', ')}.`)
  const headers = Object.entries(host.defaultHeaders)
  if (headers.length > 0)
    lines.push(`- Sent on every request: ${headers.map(([name, value]) => code(`${name}: ${value}`)).join(', ')}.`)
  lines.push('', ...codeBlock(sessionExample(host, session?.requires ?? 'unknown', example), 'ts'))
  return lines.join('\n')
}

function describeSession(session: SessionRequirement | null): string {
  if (!session)
    return 'not described in flows.json; start with cookies and run `site-to-api probe` to find out.'
  const probed = session.probed ? 'confirmed by `probe`' : 'inferred from captured traffic, not probed'
  switch (session.requires) {
    case 'none':
      return `none, plain HTTP works (${probed}).`
    case 'cookies':
      return `cookies set by the site's own responses (${probed}). Call the operation that sets them first; the jar keeps them.`
    case 'token':
      return `a token sent in a header (${probed}). Use \`tokenSession\`.`
    case 'browser':
      return `a real browser (${probed}): cookies come from scripts that only run in a browser. Use \`browserSession\` with a browser you launch, for example with Playwright, and reuse its cookies for plain HTTP.`
    case 'unknown':
      return `unknown (${probed}). Start with cookies and run \`site-to-api probe\`.`
  }
}

function sessionExample(host: HostSpec, requires: SessionRequirement['requires'], operation: string): string[] {
  const call = [`const { data, error } = await ${host.identifier}.${operation}({ /* options */ })`]
  const head = `import { ${requires === 'token'
    ? 'createSiteClient, tokenSession'
    : requires === 'browser'
      ? 'browserSession, CookieJar, createSiteClient'
      : 'CookieJar, createSiteClient'}, ${host.identifier} } from './client'`
  const hostLiteral = literal(host.host)
  switch (requires) {
    case 'token':
      return [
        head,
        '',
        `createSiteClient({`,
        `  host: ${hostLiteral},`,
        `  session: tokenSession({ getToken: () => process.env.SITE_TOKEN ?? '' }),`,
        `})`,
        ...call,
      ]
    case 'browser':
      return [
        head,
        `import { chromium } from 'playwright'`,
        '',
        `const jar = new CookieJar()`,
        `createSiteClient({`,
        `  host: ${hostLiteral},`,
        `  jar,`,
        `  // A real browser loads the site; its cookies are reused for plain HTTP and`,
        `  // fetched again when the site answers 401 or 403.`,
        `  session: browserSession({`,
        `    jar,`,
        `    async bootstrap() {`,
        `      const browser = await chromium.launch()`,
        `      try {`,
        `        const context = await browser.newContext()`,
        `        await (await context.newPage()).goto(${literal(`${host.baseUrl}/`)})`,
        `        return await context.cookies()`,
        `      }`,
        `      finally {`,
        `        await browser.close()`,
        `      }`,
        `    },`,
        `  }),`,
        `})`,
        ...call,
      ]
    default:
      return [
        head,
        '',
        `const jar = new CookieJar() // or CookieJar.fromJSON(saved)`,
        `createSiteClient({ host: ${hostLiteral}, jar })`,
        ...call,
      ]
  }
}
