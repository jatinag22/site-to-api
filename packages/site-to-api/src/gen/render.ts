/** SDK function names hey-api derives (see emit/naming); only plain identifiers go into the example. */
const PLAIN_IDENTIFIER = /^[a-z_$][\w$]*$/i

/** The `site.ts` example of the README: one host's factory and one read operation. */
function smallBundleExample(host: HostSpec | undefined): string[] {
  if (host === undefined)
    return ['// No host.']
  const operation = [
    ...host.readOperationIds,
    ...host.operationIds,
  ].map(sdkFunctionName).find(name => PLAIN_IDENTIFIER.test(name)) ?? 'someOperation'
  return [
    `import { ${hostFactoryName(host.identifier)}, ${operation} } from './client/${host.identifier}/site.js'`,
    '',
    `const { client } = ${hostFactoryName(host.identifier)}({ /* same options as createSiteClient */ })`,
    `const { data, error } = await ${operation}({ client })`,
  ]
}

function renderHostSection(host: HostSpec, session: SessionRequirement | null): string {
  // A read operation, so trying the example changes nothing on the site.
  const example = [
    ...host.readOperationIds,
    ...host.operationIds,
  ].map(sdkFunctionName).find(name => PLAIN_IDENTIFIER.test(name)) ?? 'someOperation'
  const lines = [
    `### ${text(host.host)}`,
    '',
    `- Namespace ${code(host.identifier)}, base URL ${code(host.baseUrl)}, ${host.operationIds.length} operation${host.operationIds.length === 1
      ? ''
      : 's'}.`,
    `- Session: ${describeSession(session, host.probedRequires)}`,
  ]
  if (session)
    lines.push(...cookieLines(session, host.probedRequires))
  if (session && session.botProtection.length > 0)
    lines.push(`- Bot protection: ${session.botProtection.map(entry => `${text(entry.vendor)} (${text(entry.evidence)})`).join(', ')}.`)
  const headers = Object.entries(host.defaultHeaders)
  if (headers.length > 0)
    lines.push(`- Sent on every request: ${headers.map(([name, value]) => code(`${name}: ${value}`)).join(', ')}.`)
  const sent = Object.entries(host.sentContentTypes)
  if (sent.length > 0)
    lines.push(`- JSON bodies sent under the site's own content type (the client does this for you): ${sent.map(([operation, type]) => `${code(operation)} as ${code(type)}`).join(', ')}.`)
  const auth = authLine(host)
  if (auth !== null)
    lines.push(auth)
  lines.push(...graphqlLines(host))
  lines.push(...dispatchLines(host))
  lines.push('', ...codeBlock(sessionExample(host, session?.requires ?? 'unknown', example), 'ts'))
  return lines.join('\n')
}

const LISTED_OPERATIONS = 5

/**
 * One line per GraphQL endpoint: its operations as the `{ variables }` functions `sdk` has, each
 * sending its operation name, persisted-query hash or document itself (decision 0027).
 */
function graphqlLines(host: HostSpec): string[] {
  const byEndpoint = new Map<string, HostSpec['graphql']>()
  for (const operation of host.graphql) {
    const key = `${operation.method} ${operation.endpoint}`
    byEndpoint.set(key, [
      ...(byEndpoint.get(key) ?? []),
      operation,
    ])
  }
  return [...byEndpoint].sort(([a], [b]) => a.localeCompare(b)).map(([endpoint, operations]) => {
    const calls = operations.map(operation => `${code(`sdk.${sdkFunctionName(operation.operationId)}(${operation.variablesIn === null
      ? '{}'
      : '{ variables }'})`)} (${text(operation.operationType)})`)
    return `- GraphQL on ${code(endpoint)}: ${calls.join(', ')}. Each sends its operation name, persisted-query hash or document itself; \`variables\` are typed from the capture.`
  })
}

/**
 * One line per dispatcher endpoint: its functions as the wrappers `sdk` has, each sending the
 * dispatcher parameter itself (decision 0039).
 */
function dispatchLines(host: HostSpec): string[] {
  const byEndpoint = new Map<string, HostSpec['dispatch']>()
  for (const operation of host.dispatch) {
    const key = `${operation.method} ${operation.endpoint}`
    byEndpoint.set(key, [
      ...(byEndpoint.get(key) ?? []),
      operation,
    ])
  }
  return [...byEndpoint].sort(([a], [b]) => a.localeCompare(b)).map(([endpoint, operations]) => {
    const calls = operations.slice(0, LISTED_OPERATIONS).map(operation => code(`sdk.${sdkFunctionName(operation.operationId)}(${operation.argument === null
      ? ''
      : `{ ${operation.argument} }`})`))
    const more = operations.length > LISTED_OPERATIONS
      ? ` and ${operations.length - LISTED_OPERATIONS} more`
      : ''
    return `- Dispatcher ${code(endpoint)} (${code(operations[0]!.parameter)} picks the function): ${calls.join(', ')}${more}. Each sends ${code(operations[0]!.parameter)} itself.`
  })
}

function authLine(host: HostSpec): string | null {
  if (host.securedOperationIds.length === 0)
    return null
  const listed = host.securedOperationIds.slice(0, LISTED_OPERATIONS).map(id => code(id)).join(', ')
  const more = host.securedOperationIds.length > LISTED_OPERATIONS
    ? ` and ${host.securedOperationIds.length - LISTED_OPERATIONS} more`
    : ''
  const schemes = host.auth.length === 0
    ? 'the spec declares no security scheme, so `auth` has nothing to apply'
    : host.auth.map(describeAuthScheme).join('; ')
  return `- Auth: ${listed}${more} declare security. Pass \`auth\` to \`createSiteClient\`: ${schemes}.`
}

function describeAuthScheme(scheme: AuthScheme): string {
  if (scheme.type === 'apiKey') {
    const where = `${text(scheme.in ?? 'header')} ${code(scheme.parameter ?? 'Authorization')}`
    const bearer = (scheme.in ?? 'header') === 'header' && (scheme.parameter ?? 'Authorization').toLowerCase() === 'authorization'
      ? ` (for example \`\` \`Bearer \${token}\` \`\`)`
      : ''
    return `${code(scheme.name)} is an API key in ${where}, sent as-is, so return the full value${bearer}`
  }
  if (scheme.type === 'http' && scheme.scheme === 'bearer')
    return `${code(scheme.name)} is an HTTP bearer token: return the token and the client adds \`Bearer \``
  if (scheme.type === 'http' && scheme.scheme === 'basic')
    return `${code(scheme.name)} is HTTP basic auth: return \`user:password\` and the client encodes it`
  return `${code(scheme.name)} has type ${code(scheme.type)}, which the client does not apply; add the credentials with a \`session\``
}

/** The `auth` option of the README example, or null when no operation declares security. */
function authExample(host: HostSpec): string | null {
  if (host.securedOperationIds.length === 0 || host.auth.length === 0)
    return null
  const first = host.auth[0]
  const bearerHeader = first?.type === 'apiKey'
    && (first.in ?? 'header') === 'header'
    && (first.parameter ?? 'Authorization').toLowerCase() === 'authorization'
  return bearerHeader
    ? `  auth: () => token && \`Bearer \${token}\`,`
    : '  auth: () => token,'
}

/** Plain headers probe found necessary on a host (`header:x-client-id`), sorted. */
function probedHeaders(probedRequires: string[][]): string[] {
  return [
    ...new Set(probedRequires.flat().filter(item => item.startsWith('header:')).map(item => item.slice('header:'.length))),
  ].sort()
}

/** `requests` when every probed request needed the headers, else `2 of 9 probed requests`. */
function headerNeeders(probedRequires: string[][]): string {
  const needing = probedRequires.filter(requires => requires.some(item => item.startsWith('header:'))).length
  return needing === probedRequires.length
    ? 'requests'
    : `${needing} of ${probedRequires.length} probed requests`
}

function describeSession(session: SessionRequirement | null, probedRequires: string[][]): string {
  const headers = probedHeaders(probedRequires)
  if (!session)
    return 'not described in flows.json; start with cookies and run `site-to-api probe` to find out.'
  const probed = session.probed ? 'confirmed by `probe`' : 'inferred from captured traffic, not probed'
  switch (session.requires) {
    case 'none':
      return headers.length > 0
        ? `plain HTTP works; ${headerNeeders(probedRequires)} need ${headers.length === 1
          ? 'header'
          : 'headers'} ${headers.map(code).join(', ')} (${probed}).`
        : `none, plain HTTP works (${probed}).`
    case 'cookies':
      return `cookies set by the site's own responses (${probed}). Call the operation that sets them first; the jar keeps them.`
    case 'token':
      return `a token sent in a header (${probed}). Use \`tokenSession\`.`
    case 'browser':
      return `a real browser (${probed}): cookies come from scripts that only run in a browser. Use \`browserSession\` with a browser you launch, for example with Playwright, and reuse its cookies for plain HTTP.`
    case 'unknown':
      return `unknown (${probed}). Start with cookies and run \`site-to-api probe\`.`
  }
}

function sessionExample(host: HostSpec, requires: SessionRequirement['requires'], operation: string): string[] {
  const auth = authExample(host)
  const tokenLine = auth === null
    ? []
    : ['let token: string | undefined // for example from the login response', '']
  const authLines = auth === null
    ? []
    : [auth]
  const call = [`const { data, error } = await sdk.${operation}({ /* options */ })`]
  const head = `import { ${requires === 'token'
    ? 'createSiteClient, tokenSession'
    : requires === 'browser'
      ? 'browserSession, CookieJar, createSiteClient'
      : 'CookieJar, createSiteClient'} } from './client/index.js'`
  const hostLiteral = literal(host.host)
  switch (requires) {
    case 'token':
      return [
        head,
        '',
        ...tokenLine,
        `const { sdk } = createSiteClient({`,
        `  host: ${hostLiteral},`,
        `  session: tokenSession({ getToken: () => process.env.SITE_TOKEN ?? '' }),`,
        ...authLines,
        `})`,
        ...call,
      ]
    case 'browser':
      return [
        head,
        `import { chromium } from 'playwright'`,
        '',
        ...tokenLine,
        `const jar = new CookieJar()`,
        `const { sdk } = createSiteClient({`,
        `  host: ${hostLiteral},`,
        `  jar,`,
        `  // A real browser loads the site; its cookies are reused for plain HTTP and`,
        `  // fetched again when the site answers 401 or 403.`,
        `  session: browserSession({`,
        `    jar,`,
        `    async bootstrap() {`,
        `      const browser = await chromium.launch()`,
        `      try {`,
        `        const context = await browser.newContext()`,
        `        await (await context.newPage()).goto(${literal(`${host.baseUrl}/`)})`,
        `        return await context.cookies()`,
        `      }`,
        `      finally {`,
        `        await browser.close()`,
        `      }`,
        `    },`,
        `  }),`,
        ...authLines,
        `})`,
        ...call,
      ]
    default:
      return [
        head,
        '',
        ...tokenLine,
        `const jar = new CookieJar() // or CookieJar.fromJSON(saved)`,
        ...(auth === null
          ? [`const { sdk } = createSiteClient({ host: ${hostLiteral}, jar })`]
          : [
              `const { sdk } = createSiteClient({`,
              `  host: ${hostLiteral},`,
              `  jar,`,
              ...authLines,
              `})`,
            ]),
        ...call,
      ]
  }
}
