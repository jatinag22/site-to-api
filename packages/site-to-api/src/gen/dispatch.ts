/**
 * `client/<host>/dispatch.ts`: one function per dispatcher function (decision 0039) that sends
 * the dispatcher parameter itself (`functionName=getSymbolData`), so the caller passes only the
 * function's own parameters. Each wraps the hey-api SDK function of the same operation, so
 * validation, auth and the configured fetch apply unchanged, and goes through the runtime's
 * `fetchWithoutFragment`, because the spec path is `<endpoint>#<value>` and hey-api appends the
 * query string after the fragment. `createSiteClient` puts these functions in `sdk` in place of
 * the raw ones.
 */
import type { DispatchClientOperation, HostSpec } from './spec'
import { commentText } from '../emit/escape'
import { dataTypeName, sdkFunctionName } from '../emit/naming'
import { toPascalCase } from './spec'

const HEADER = '// Generated by site-to-api gen from specs/. Do not edit: run `site-to-api gen` again.\n'

/** SDK function names hey-api derives; only plain identifiers can be re-exported by name. */
const PLAIN_IDENTIFIER = /^[a-z_$][\w$]*$/i

function literal(value: unknown): string {
  return JSON.stringify(value)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
}

const WHERE: Record<DispatchClientOperation['in'], string> = {
  query: 'in the query string',
  form: 'as a form field',
  json: 'in the JSON body',
}

function renderOperation(operation: DispatchClientOperation): string {
  const fn = sdkFunctionName(operation.operationId)
  const data = dataTypeName(operation.operationId)
  const optionsType = `${toPascalCase(fn)}Options`
  // The dispatcher's location is replaced by the caller's own fields there, without the dispatcher.
  const slot = operation.in === 'query'
    ? 'query'
    : 'body'
  const own = `Omit<NonNullable<${data}['${slot}']>, ${literal(operation.parameter)}>`
  const sent = `{ ...${slot}, ${literal(operation.parameter)}: ${literal(operation.value)} }`
  const parameter = operation.optionsRequired
    ? `options: ${optionsType}<ThrowOnError>`
    : `options: ${optionsType}<ThrowOnError> = {}`
  return [
    `/** Options of {@link ${fn}}: the SDK options, with \`${slot}\` holding only the function's own fields. */`,
    `export type ${optionsType}<ThrowOnError extends boolean = false> = Omit<Options<${data}, ThrowOnError>, '${slot}'> & {`,
    `  ${slot}${operation.argumentRequired ? '' : '?'}: ${own}`,
    '}',
    '',
    '/**',
    ` * Function ${commentText(`\`${operation.value}\``)} of ${commentText(`${operation.method} ${operation.endpoint}`)}.`,
    ` * Sends ${commentText(`\`${operation.parameter}=${operation.value}\``)} ${WHERE[operation.in]} itself.`,
    ' */',
    `export function ${fn}<ThrowOnError extends boolean = false>(${parameter}) {`,
    `  const { ${slot}, ...rest } = options`,
    `  return sdk.${fn}<ThrowOnError>({`,
    '    ...rest,',
    `    ${slot}: ${sent},`,
    '    fetch: fetchWithoutFragment(rest.fetch ?? (rest.client ?? client).getConfig().fetch),',
    '  })',
    '}',
  ].join('\n')
}

/** The dispatcher functions of a host that get a function; the others are reported in `warnings`. */
export function dispatchFunctions(host: Pick<HostSpec, 'file' | 'dispatch'>, warnings: string[]): DispatchClientOperation[] {
  return host.dispatch.filter((operation) => {
    if (PLAIN_IDENTIFIER.test(sdkFunctionName(operation.operationId)))
      return true
    warnings.push(`specs/${host.file}: dispatcher function ${operation.operationId} has no plain SDK function name, so it gets no wrapper; call its SDK function with ${operation.parameter} set yourself`)
    return false
  })
}

/** `client/<host>/dispatch.ts` for the given operations (at least one). */
export function renderDispatchModule(operations: readonly DispatchClientOperation[]): string {
  return [
    HEADER,
    `import type { Options } from './sdk.gen.js'`,
    `import type { ${operations.map(operation => dataTypeName(operation.operationId)).sort().join(', ')} } from './types.gen.js'`,
    `import { fetchWithoutFragment } from '@site-to-api/runtime'`,
    `import { client } from './client.gen.js'`,
    `import * as sdk from './sdk.gen.js'`,
    '',
    operations.map(renderOperation).join('\n\n'),
    '',
  ].join('\n')
}
