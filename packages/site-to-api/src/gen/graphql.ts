/**
 * `client/<host>/graphql.ts`: one function per GraphQL operation that takes `{ variables }` and
 * sends the operation's constants itself (decision 0027). Each wraps the hey-api SDK function of
 * the same operation, so request and response validation, auth and the configured fetch apply
 * unchanged; `createSiteClient` puts these functions in `sdk` in place of the raw ones.
 */
import type { GraphqlClientOperation, HostSpec } from './spec'
import { commentText } from '../emit/escape'
import { dataTypeName, sdkFunctionName } from '../emit/naming'
import { toPascalCase } from './spec'

const HEADER = '// Generated by site-to-api gen from specs/. Do not edit: run `site-to-api gen` again.\n'

/** SDK function names hey-api derives; only plain identifiers can be re-exported by name. */
const PLAIN_IDENTIFIER = /^[a-z_$][\w$]*$/i

const GRAPHQL_FIELDS = [
  'operationName',
  'query',
  'variables',
  'extensions',
] as const

function literal(value: unknown): string {
  return JSON.stringify(value)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
}

/** The value the function sends for one GraphQL field, or null when the caller supplies it. */
function fieldValue(field: (typeof GRAPHQL_FIELDS)[number], operation: GraphqlClientOperation): string | null {
  switch (field) {
    case 'operationName':
      return operation.operationName === null
        ? null
        : literal(operation.operationName)
    case 'query':
      return operation.document === null
        ? null
        : literal(operation.document)
    case 'extensions': {
      const persisted = operation.persistedQuery
      if (persisted === null)
        return null
      return persisted.version === null
        ? `{ persistedQuery: { sha256Hash: ${literal(persisted.sha256Hash)} } }`
        : `{ persistedQuery: { version: ${persisted.version}, sha256Hash: ${literal(persisted.sha256Hash)} } }`
    }
    case 'variables':
      return 'variables'
  }
}

/** `{ operationName: "x", variables, ... }` for one location, or null when nothing goes there. */
function locationObject(operation: GraphqlClientOperation, sent: readonly string[], spread: string | null): string | null {
  const entries = GRAPHQL_FIELDS.flatMap((field) => {
    if (!sent.includes(field))
      return []
    const value = fieldValue(field, operation)
    if (value === null)
      return []
    return [
      value === field
        ? field
        : `${field}: ${value}`,
    ]
  })
  if (spread !== null)
    entries.unshift(`...${spread}`)
  return entries.length === 0
    ? null
    : `{ ${entries.join(', ')} }`
}

function describe(operation: GraphqlClientOperation): string[] {
  const type = operation.operationType === 'unknown'
    ? 'operation (type unknown)'
    : operation.operationType
  const name = operation.operationName === null
    ? ''
    : ` ${commentText(`\`${operation.operationName}\``)}`
  const lines = [
    ` * GraphQL ${commentText(type)}${name} (${commentText(`${operation.method} ${operation.endpoint}`)}).`,
  ]
  if (operation.persistedQuery !== null)
    lines.push(` * Persisted query ${commentText(`\`${operation.persistedQuery.sha256Hash}\``)}.`)
  const where = operation.variablesIn === null
    ? 'It was captured without variables.'
    : `Pass \`variables\`; they are sent ${operation.variablesIn === 'body'
      ? 'in the JSON body'
      : 'as JSON in the query string'}.`
  lines.push(` * Sends the operation's constants itself. ${where}`)
  return lines
}

function renderOperation(operation: GraphqlClientOperation): string {
  const fn = sdkFunctionName(operation.operationId)
  const base = toPascalCase(fn)
  const data = dataTypeName(operation.operationId)
  const variablesType = `${base}Variables`
  const optionsType = `${base}Options`
  const hasQueryArgument = operation.otherQuery.length > 0
  const queryRequired = operation.otherQuery.some(parameter => parameter.required)
  const members = [
    ...(operation.variablesIn === null
      ? []
      : [`  variables${operation.variablesRequired
          ? ''
          : '?'}: ${variablesType}`]),
    ...(hasQueryArgument
      ? [`  query${queryRequired
          ? ''
          : '?'}: Omit<NonNullable<${data}['query']>, ${GRAPHQL_FIELDS.map(field => `'${field}'`).join(' | ')}>`]
      : []),
  ]
  const body = locationObject(operation, operation.sent.body, null)
  const query = locationObject(operation, operation.sent.query, hasQueryArgument
    ? 'query'
    : null)
  const json = operation.sent.query.filter(field => field === 'variables' || field === 'extensions')
  const destructured = [
    ...(operation.variablesIn === null
      ? []
      : ['variables']),
    ...(hasQueryArgument
      ? ['query']
      : []),
  ]
  const call = [
    '    ...rest,',
    ...(body === null
      ? []
      : [`    body: ${body},`]),
    ...(query === null
      ? []
      : [`    query: ${query},`]),
    ...(json.length === 0
      ? []
      : [`    querySerializer: graphqlQuerySerializer(${literal(json)}),`]),
    // A `#name` spec path keeps operations on one endpoint apart; the request goes to the endpoint.
    ...(operation.path.includes('#')
      ? ['    fetch: fetchWithoutFragment(rest.fetch ?? (rest.client ?? client).getConfig().fetch),']
      : []),
  ]
  return [
    ...(operation.variablesIn === null
      ? []
      : [
          `/** The \`variables\` of ${commentText(`\`${fn}\``)}. */`,
          `export type ${variablesType} = NonNullable<${data}['${operation.variablesIn}']>['variables']`,
          '',
        ]),
    `/** Options of {@link ${fn}}: the SDK options without \`body\` and \`query\`, plus the variables. */`,
    `export type ${optionsType}<ThrowOnError extends boolean = false> = Omit<Options<${data}, ThrowOnError>, 'body' | 'query'> & {`,
    ...members,
    '}',
    '',
    '/**',
    ...describe(operation),
    ' */',
    `export function ${fn}<ThrowOnError extends boolean = false>(options: ${optionsType}<ThrowOnError>) {`,
    destructured.length === 0
      ? '  const rest = options'
      : `  const { ${destructured.join(', ')}, ...rest } = options`,
    `  return sdk.${fn}<ThrowOnError>({`,
    ...call,
    '  })',
    '}',
  ].join('\n')
}

/** The GraphQL operations of a host that get a function; the others are reported in `warnings`. */
export function graphqlFunctions(host: Pick<HostSpec, 'file' | 'graphql'>, warnings: string[]): GraphqlClientOperation[] {
  return host.graphql.filter((operation) => {
    if (PLAIN_IDENTIFIER.test(sdkFunctionName(operation.operationId)))
      return true
    warnings.push(`specs/${host.file}: GraphQL operation ${operation.operationId} has no plain SDK function name, so it gets no \`{ variables }\` function; call its SDK function with the full body`)
    return false
  })
}

/** `client/<host>/graphql.ts` for the given operations (at least one). */
export function renderGraphqlModule(operations: readonly GraphqlClientOperation[]): string {
  const runtime = [
    ...(operations.some(operation => operation.path.includes('#'))
      ? ['fetchWithoutFragment']
      : []),
    ...(operations.some(operation => operation.sent.query.some(field => field === 'variables' || field === 'extensions'))
      ? ['graphqlQuerySerializer']
      : []),
  ]
  const usesClient = operations.some(operation => operation.path.includes('#'))
  return [
    HEADER,
    `import type { Options } from './sdk.gen.js'`,
    `import type { ${operations.map(operation => dataTypeName(operation.operationId)).sort().join(', ')} } from './types.gen.js'`,
    ...(runtime.length === 0
      ? []
      : [`import { ${runtime.join(', ')} } from 'site-to-api-runtime'`]),
    ...(usesClient
      ? [`import { client } from './client.gen.js'`]
      : []),
    `import * as sdk from './sdk.gen.js'`,
    '',
    operations.map(renderOperation).join('\n\n'),
    '',
  ].join('\n')
}
