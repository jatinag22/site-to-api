/**
 * Builds the most stable CSS selector for an element: id, then `name`, then other naming
 * attributes, then a class or data attribute unique in the document, then a path from the nearest
 * uniquely identifiable ancestor, then a full `:nth-of-type` path. Every candidate is verified to
 * match exactly the element.
 */
import type { AnyNode } from 'domhandler'
import type { Element } from './dom'
import { attr, classes, cssIdent, cssString, nthOfType, parentElement, select } from './dom'

/** Attributes whose value names the element rather than carrying data. */
const NAMING_ATTRIBUTES = [
  'property',
  'itemprop',
  'data-testid',
  'data-test',
  'data-qa',
  'data-field',
  'data-name',
  'aria-label',
  'for',
]

/** Ids and classes generated by frameworks change between builds or renders. */
const GENERATED_PREFIX = /^(?:ember|ext-gen|yui_|react-|radix-|headlessui-|mui-|:r|css-|sc-|jsx-|svelte-|emotion-|tw-)/i

function looksGenerated(token: string): boolean {
  if (GENERATED_PREFIX.test(token) || /\d{4,}/.test(token))
    return true
  // A hash-like piece: five or more characters mixing letters and digits (`_3fG7k`, `a1B2c`).
  return token.split(/[-_]+/).some(piece => piece.length >= 5 && /\d/.test(piece) && /[a-z]/i.test(piece))
}

/** True for an id worth anchoring a selector on. */
export function isStableId(id: string): boolean {
  return /^[a-z_][\w-]*$/i.test(id) && !looksGenerated(id)
}

/** Classes worth using in a selector, in document order. */
export function stableClasses(element: Element): string[] {
  return classes(element).filter(name => /^[a-z_][\w-]*$/i.test(name) && !looksGenerated(name))
}

function matchesOnly(selector: string, element: Element, root: AnyNode): boolean {
  const found = select(selector, root)
  return found.length === 1 && found[0] === element
}

/** Selectors that use only the element's own attributes, most stable first. */
function ownCandidates(element: Element): string[] {
  const tag = element.name
  const out: string[] = []
  const id = attr(element, 'id')
  if (id !== null && isStableId(id))
    out.push(`#${cssIdent(id)}`)
  const name = attr(element, 'name')
  if (name !== null && name !== '')
    out.push(`${tag}[name=${cssString(name)}]`)
  for (const attribute of NAMING_ATTRIBUTES) {
    const value = attr(element, attribute)
    if (value !== null && value !== '' && value.length <= 80)
      out.push(`${tag}[${attribute}=${cssString(value)}]`)
  }
  for (const name of stableClasses(element))
    out.push(`${tag}.${cssIdent(name)}`)
  for (const attribute of Object.keys(element.attribs).sort()) {
    if (attribute.startsWith('data-') && /^[\w-]+$/.test(attribute))
      out.push(`${tag}[${attribute}]`)
  }
  return out
}

function step(element: Element): string {
  return `${element.name}:nth-of-type(${nthOfType(element)})`
}

/** `ancestor > a:nth-of-type(1) > b:nth-of-type(2)` from an ancestor down to the element. */
function pathFrom(ancestor: Element | null, element: Element): string {
  const steps: string[] = []
  for (let current: Element | null = element; current && current !== ancestor; current = parentElement(current))
    steps.unshift(step(current))
  return steps.join(' > ')
}

/**
 * Candidate selectors in order of stability. The caller verifies them against its documents;
 * `uniqueSelector` does so for one document.
 */
export function selectorCandidates(element: Element, root: AnyNode): string[] {
  const out = ownCandidates(element)
  let next = parentElement(element)
  for (let depth = 0; next && depth < 6; depth++, next = parentElement(next)) {
    const ancestor = next
    const anchor = ownCandidates(ancestor).find(candidate => matchesOnly(candidate, ancestor, root))
    if (anchor === undefined)
      continue
    for (const own of ownCandidates(element))
      out.push(`${anchor} ${own}`)
    out.push(`${anchor} > ${pathFrom(ancestor, element)}`)
    break
  }
  out.push(pathFrom(null, element))
  return [
    ...new Set(out),
  ]
}

/** The most stable selector that matches exactly `element` under `root`, or `null`. */
export function uniqueSelector(element: Element, root: AnyNode, accept: (selector: string) => boolean = () => true): string | null {
  return selectorCandidates(element, root).find(candidate => matchesOnly(candidate, element, root) && accept(candidate)) ?? null
}
